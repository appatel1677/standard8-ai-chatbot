def build_class_8_syllabus(raw):
    """Build Class 8 syllabus from raw DIKSHA data and fill missing subjects."""
    subjects = {}
    for raw_name, meta in raw.items():
        clean_name, icon, code = get_subject_info(raw_name)
        if not clean_name:
            continue
        if clean_name not in subjects:
            subjects[clean_name] = {
                "icon": icon,
                "code": code,
                "chapters": []
            }
        sem_label = ""
        if "પ્રથમ સત્ર" in raw_name or "प्रथम सत्र" in raw_name:
            sem_label = "સત્ર ૧: "
        elif "દ્વિતીય સત્ર" in raw_name or "द्वितीय सत्र" in raw_name:
            sem_label = "સત્ર ૨: "
        for ch in meta.get("chapters", []):
            ch_name = ch.get("name", "").strip()
            display_name = f"{sem_label}{ch_name}" if sem_label else ch_name
            subjects[clean_name]["chapters"].append({
                "name": display_name,
                "raw_name": ch_name,
                "book": meta.get("diksha_books", [raw_name])[0] if isinstance(meta.get("diksha_books"), list) else raw_name,
                "id": ch.get("id", ""),
                "pdfs": ch.get("pdfs", [])
            })

    grade_8_titles = SAMPLE_CHAPTER_TITLES.get(8, {})
    for name, (icon, code) in UPPER_PRIMARY_SUBJECTS.items():
        if name not in subjects or len(subjects[name]["chapters"]) == 0:
            titles = grade_8_titles.get(code, [])
            subjects[name] = {
                "icon": icon,
                "code": code,
                "chapters": [
                    {
                        "name": title,
                        "raw_name": title,
                        "book": f"{name.split('(')[0].strip()} ધોરણ 8",
                        "id": "",
                        "pdfs": []
                    }
                    for title in titles
                ]
            }

    ordered_subjects = {}
    for name in UPPER_PRIMARY_SUBJECTS:
        if name in subjects:
            ordered_subjects[name] = subjects[name]
    for name, val in subjects.items():
        if name not in ordered_subjects:
            ordered_subjects[name] = val

    return ordered_subjects


def build_placeholder_syllabus(grade_num, num_chapters=10):
    """Build syllabus for grades 3-7 with GCERT chapter titles."""
    subjects = {}
    grade_titles = SAMPLE_CHAPTER_TITLES.get(grade_num, {})
    subject_dict = PRIMARY_SUBJECTS if grade_num in (3, 4, 5) else UPPER_PRIMARY_SUBJECTS

    for name, (icon, code) in subject_dict.items():
        titles = grade_titles.get(code, [f"પ્રકરણ {i}" for i in range(1, num_chapters + 1)])
        chapters = []
        for title in titles:
            chapters.append({
                "name": title,
                "raw_name": title,
                "book": f"{name.split('(')[0].strip()} ધોરણ {grade_num}",
                "id": "",
                "pdfs": []
            })
        subjects[name] = {
            "icon": icon,
            "code": code,
            "chapters": chapters
        }
    return subjects


def main():
    raw_path = "diksha_syllabus_raw.json"
    if not os.path.exists(raw_path):
        print(f"⚠️ {raw_path} not found. Generating GCERT data for all classes.")
        raw = {}
    else:
        with open(raw_path, "r", encoding="utf-8") as f:
            raw = json.load(f)

    result = {}
    for grade in range(8, 2, -1):  # 8, 7, 6, 5, 4, 3
        grade_key = f"ધોરણ {grade}"
        if grade == 8 and raw:
            subjects = build_class_8_syllabus(raw)
        else:
            subjects = build_placeholder_syllabus(grade)
        result[grade_key] = {"subjects": subjects}
        print(f"Grade {grade}: {len(subjects)} subjects")

    with open("diksha_syllabus.json", "w", encoding="utf-8") as f:
        json.dump(result, f, ensure_ascii=False, indent=2)

    print("\nGenerated diksha_syllabus.json successfully!")
    for grade_key, data in result.items():
        total_ch = sum(len(s["chapters"]) for s in data["subjects"].values())
        print(f"  {grade_key}: {len(data['subjects'])} subjects, {total_ch} chapters")


if __name__ == "__main__":
    main()